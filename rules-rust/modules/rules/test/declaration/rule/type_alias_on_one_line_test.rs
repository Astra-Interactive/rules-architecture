use crate::declaration::rule::TypeAliasOnOneLine;
use crate::test::declaration::util::assert_code_findings;
use crate::test::declaration::util::assert_code_fixture;

#[test]
fn given_persistent_code_fixtures_when_checked_then_match_exact_anchors() {
    assert_code_fixture(&TypeAliasOnOneLine, "TypeAliasOnOneLine", "bad");
    assert_code_fixture(&TypeAliasOnOneLine, "TypeAliasOnOneLine", "good");
}

#[test]
fn given_module_alias_broken_after_equals_when_checked_then_reports_type_line() {
    assert_code_findings(
        &TypeAliasOnOneLine,
        "TypeAliasOnOneLine",
        r#"type KeepInventoryGate =
    FeatureGate<KeepInventoryModule, ConfigurationFeatureFlagReader<KeepInventoryConfiguration>>;"#,
        &[1],
    );
}

